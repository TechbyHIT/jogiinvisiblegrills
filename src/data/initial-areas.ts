export function getAreaBySlug(locationId: string, areaSlug: string) {
  return AREAS.find(
    (area) => area.locationId === locationId && area.slug === areaSlug,
  );
}

export function getAreasByLocationId(locationId: string) {
  return AREAS.filter((area) => area.locationId === locationId);
}

const AP_LOCATION_IDS = new Set([
  "loc-visakhapatnam",
  "loc-gajuwaka",
  "loc-anakapalle",
  "loc-vizianagaram",
]);

export function getPublishedAreas() {
  return AREAS.filter(
    (area) =>
      area.publicationStatus === "published" &&
      area.allowIndexing &&
      area.isServed &&
      !AP_LOCATION_IDS.has(area.locationId),
  );
}

export function getAreaById(id: string) {
  return AREAS.find((area) => area.id === id);
}
